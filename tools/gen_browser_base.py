#!/usr/bin/env python3
"""从 IGlBackend 接口生成 WebGL 的兜底基类（未实现命令一律抛 NotSupported）。"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
api = (ROOT / "src/Byta/Generated/Gl.Api.g.cs").read_text(encoding="utf-8")
block = api[api.index("public unsafe interface IGlBackend"):]
block = block[:block.index("\n}")]

methods = []
for line in block.splitlines():
    m = re.match(r"^([\w\*]+) (\w+)\((.*)\);$", line.strip())
    if not m:
        continue
    ret, name, params = m.group(1), m.group(2), m.group(3)
    if name in ("Name", "Supports"):        # 这两个由基类自己实现
        continue
    methods.append((ret, name, params))

def gl_name(cs: str) -> str:
    return "gl" + cs[0].lower() + cs[1:]

out = [
    "// SPDX-License-Identifier: MIT",
    "// <auto-generated> 由 tools/gen_browser_base.py 从 IGlBackend 生成，请勿手改。 </auto-generated>",
    "#pragma warning disable CS1591",
    "#nullable enable",
    "",
    "namespace Byta.Browser;",
    "",
    "/// <summary>",
    "/// 未实现命令的兜底：全部抛 <see cref=\"GlNotSupportedException\"/>。",
    "/// WebGL2 只覆盖 GLES 3.0，桌面 GL 专有的命令（DSA、glBufferStorage、调试回调等）都在这里。",
    "/// </summary>",
    "public abstract unsafe class WebGlBackendBase : IGlBackend",
    "{",
    "    public abstract string Name { get; }",
    "",
    "    /// <summary>由具体实现覆盖，声明自己真正实现了哪些命令。</summary>",
    "    public virtual bool Supports(string command) => false;",
    "",
    "    protected GlNotSupportedException Unsupported(string command) =>",
    "        new(command, $\"WebGL2 后端不支持该命令（GLES 3.0 没有，或尚未接入）\");",
    "",
]
for ret, name, params in methods:
    out.append(f"    public virtual {ret} {name}({params}) => throw Unsupported(\"{gl_name(name)}\");")
out += ["}", ""]

target = ROOT / "src/Byta.Browser/WebGlBackendBase.g.cs"
target.write_text("\n".join(out), encoding="utf-8")
print(f"{target}: {len(methods)} 条命令")
